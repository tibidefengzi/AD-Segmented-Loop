# 名字 -> **所有持有它的**子模块（属主 + 用 `from .X import name` 拷了副本的）
_HOLDERS = {}
for _mn in _SUBMODULES:
    _mod = sys.modules[__name__ + "." + _mn]
    for _k in _OWNER:
        if _k in vars(_mod):
            _HOLDERS.setdefault(_k, []).append(_mn)


class _RelayCoreModule(_types.ModuleType):
    """把对**已导出名**的赋值转发给所有持有它的子模块（见上方说明）。"""

    def __setattr__(self, name, value):
        for _mn in _HOLDERS.get(name, ()):        # `_HOLDERS` 是类外全局，不触发本方法
            setattr(sys.modules[__name__ + "." + _mn], name, value)
        super().__setattr__(name, value)


sys.modules[__name__].__class__ = _RelayCoreModule
